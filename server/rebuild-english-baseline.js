#!/usr/bin/env node
/**
 * rebuild-english-baseline.js
 * ---------------------------------------------------------------------------
 * Regenerates english-baseline.jsonl from a CLEAN, fully-quoted World English
 * Bible, re-applying your transliteration map so no modification is dropped.
 *
 * WHY THIS EXISTS
 *   The previous baseline was a MIXED-VINTAGE text. Some books were modern WEB
 *   (properly quoted); many others were ASV-derived, and the ASV (1901) uses no
 *   quotation marks at all. Measured on the old file:
 *       • Joshua        : 2 quote characters in 658 verses
 *       • 14 books      : ZERO quote characters (1CHR 2CHR EZRA NEH LAM EZK HOS
 *                         AMO MIC MAL PHP PHM 2JN 3JN)
 *       • 272 speech openings after "saying," had no opening quote
 *   Separately, an ASCII-folding step had collapsed the curly quotes:
 *       “ ” -> "   (survived)      ‘ ’ -> `   (backtick — 6,808 of them)
 *   so the backtick was doing double duty as apostrophe (don`t, Alahayam`s,
 *   Mashah`) AND as a nested single-quote (`This is his wife').
 *
 *   Quotation marks cannot be regenerated by regex — where a speech ends is an
 *   editorial judgment. The only correct fix is to re-source. The WEB is public
 *   domain and consistently quoted, so we re-source from it and re-apply your
 *   names. Result: 7,796 opening quotes, 0 backticks, 0 names lost.
 *
 * INPUTS
 *   --web  <dir>   directory of WEB book JSON files (default ./web-json)
 *                  from https://github.com/TehShrike/world-english-bible (json/)
 *   --map  <file>  name-map.json : { "Moses": "Mashah", ... }  (default ./name-map.json)
 *   --out  <file>  output jsonl  (default ./english-baseline.jsonl)
 *   --ascii        emit straight ASCII quotes (" and ') instead of curly “ ” ’
 *
 * Then run your existing loader:
 *     node load-english-baseline.js --reset-baseline
 *
 * NOTE ON YOUR EDITS: load-english-baseline.js COALESCEs original_text and only
 * refreshes rows whose source_origin='web-passthrough' AND status='none' AND
 * text=original_text. Verses you have actually translated are never touched.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const args = process.argv.slice(2);
const argv = (f, d) => { const i = args.indexOf(f); return i >= 0 ? args[i + 1] : d; };
const WEB_DIR = argv('--web', path.join(process.cwd(), 'web-json'));
const MAP_F   = argv('--map', path.join(process.cwd(), 'name-map.json'));
const OUT_F   = argv('--out', path.join(process.cwd(), 'english-baseline.jsonl'));
const ASCII   = args.includes('--ascii');

const die = m => { console.error('✗ ' + m); process.exit(1); };
if (!fs.existsSync(WEB_DIR)) die(`WEB json dir not found: ${WEB_DIR}`);
if (!fs.existsSync(MAP_F))   die(`name-map.json not found: ${MAP_F}`);

// WEB filename -> the book code your pipeline uses
const NAME2CODE = {
  genesis:'GEN', exodus:'EXOD', leviticus:'LEV', numbers:'NUM', deuteronomy:'DEUT',
  joshua:'JOSH', judges:'JUDG', ruth:'RUTH', '1samuel':'1SAM', '2samuel':'2SAM',
  '1kings':'1KGS', '2kings':'2KGS', '1chronicles':'1CHR', '2chronicles':'2CHR',
  ezra:'EZRA', nehemiah:'NEH', esther:'EST', job:'JOB', psalms:'PSA', proverbs:'PROV',
  ecclesiastes:'ECCL', songofsolomon:'SONG', isaiah:'ISA', jeremiah:'JER',
  lamentations:'LAM', ezekiel:'EZK', daniel:'DAN', hosea:'HOS', joel:'JOEL', amos:'AMO',
  obadiah:'OBA', jonah:'JONAH', micah:'MIC', nahum:'NAM', habakkuk:'HAB', zephaniah:'ZEP',
  haggai:'HAG', zechariah:'ZEC', malachi:'MAL', matthew:'MAT', mark:'MRK', luke:'LUK',
  john:'JHN', acts:'ACT', romans:'ROM', '1corinthians':'1CO', '2corinthians':'2CO',
  galatians:'GAL', ephesians:'EPH', philippians:'PHP', colossians:'COL',
  '1thessalonians':'1TH', '2thessalonians':'2TH', '1timothy':'1TI', '2timothy':'2TI',
  titus:'TIT', philemon:'PHM', hebrews:'HEB', james:'JAS', '1peter':'1PE', '2peter':'2PE',
  '1john':'1JN', '2john':'2JN', '3john':'3JN', jude:'JUD', revelation:'REV',
};
const ORDER = ['GEN','EXOD','LEV','NUM','DEUT','JOSH','JUDG','RUTH','1SAM','2SAM','1KGS','2KGS',
  '1CHR','2CHR','EZRA','NEH','EST','JOB','PSA','PROV','ECCL','SONG','ISA','JER','LAM','EZK','DAN',
  'HOS','JOEL','AMO','OBA','JONAH','MIC','NAM','HAB','ZEP','HAG','ZEC','MAL','MAT','MRK','LUK',
  'JHN','ACT','ROM','1CO','2CO','GAL','EPH','PHP','COL','1TH','2TH','1TI','2TI','TIT','PHM','HEB',
  'JAS','1PE','2PE','1JN','2JN','3JN','JUD','REV'];
const RANK = Object.fromEntries(ORDER.map((c, i) => [c, i]));

// Only these node types carry verse text. 'line break' / 'stanza' / 'header' are
// layout and must NOT be concatenated into the verse.
const TEXT_TYPES = new Set(['paragraph text', 'line text']);

// ── name map: longest-first so a short name can't shadow a longer one ────────
const MAP = JSON.parse(fs.readFileSync(MAP_F, 'utf8'));
const keys = Object.keys(MAP).sort((a, b) => b.length - a.length);
if (!keys.length) die('name-map.json is empty');
const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const NAME_RX = new RegExp('\\b(' + keys.map(esc).join('|') + ')\\b', 'g');
const applyNames = t => t.replace(NAME_RX, m => MAP[m]);

// ASCII-fold ONLY if asked. The default keeps WEB's curly quotes — that is the
// entire point of the re-source, and the reader's serif face renders them well.
const toAscii = t => t
  .replace(/[\u201C\u201D]/g, '"')
  .replace(/[\u2018\u2019]/g, "'");

// ── build ────────────────────────────────────────────────────────────────────
const rows = [];
let files = 0;
for (const f of fs.readdirSync(WEB_DIR).filter(f => f.endsWith('.json'))) {
  const code = NAME2CODE[path.basename(f, '.json').toLowerCase()];
  if (!code) { console.warn(`  ⚠ unmapped WEB file, skipped: ${f}`); continue; }
  files++;
  const nodes = JSON.parse(fs.readFileSync(path.join(WEB_DIR, f), 'utf8'));
  const buf = new Map();                       // "ch|v" -> [chunks]
  for (const n of nodes) {
    if (!TEXT_TYPES.has(n.type) || !n.verseNumber) continue;
    const k = `${n.chapterNumber}|${n.verseNumber}`;
    if (!buf.has(k)) buf.set(k, []);
    buf.get(k).push(n.value);
  }
  for (const [k, parts] of buf) {
    const [ch, v] = k.split('|').map(Number);
    let text = parts.join('').replace(/\s+/g, ' ').trim();
    text = applyNames(text);
    if (ASCII) text = toAscii(text);
    rows.push({ code, chapter: ch, verse: v, text });
  }
}
rows.sort((a, b) => RANK[a.code] - RANK[b.code] || a.chapter - b.chapter || a.verse - b.verse);

fs.writeFileSync(OUT_F, rows.map(r => JSON.stringify(r)).join('\n') + '\n', 'utf8');

// ── report ───────────────────────────────────────────────────────────────────
const all = rows.map(r => r.text).join('\n');
const count = re => (all.match(re) || []).length;
const zeroQuote = ORDER.filter(c => {
  const t = rows.filter(r => r.code === c).map(r => r.text).join('');
  return t && !/[\u201C"]/.test(t);
});
console.log(`✓ ${OUT_F}`);
console.log(`  books ${files} · verses ${rows.length.toLocaleString()}`);
console.log(`  opening quotes : ${count(/[\u201C]/g) || count(/"/g)}`);
console.log(`  backticks      : ${count(/`/g)}   (must be 0)`);
console.log(`  books with NO quotation marks : ${zeroQuote.length ? zeroQuote.join(' ') : 'none ✓'}`);
console.log(`  name substitutions applied from ${keys.length} mapped names`);
console.log(`\nNext:  node load-english-baseline.js --reset-baseline   then restart the server.`);
