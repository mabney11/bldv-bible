// These files do NOT all live in lexicon/ — the Strong's dictionaries sit at the
// server root — so search a few places and report where each was found.
function findJSON(name) {
    for (const d of [LEX_DIR, path.join(LEX_DIR, '..'), __dirname, process.cwd()]) {
        const p = path.join(d, name);
        if (!fs.existsSync(p)) continue;
        try { return { json: JSON.parse(fs.readFileSync(p, 'utf8')), at: p }; }
        catch (e) { console.warn(`  \u26a0 ${p}: ${e.message}`); return { json: null, at: null }; }
    }
    return { json: null, at: null };
}
