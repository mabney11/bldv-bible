// Validate: every surviving real SN's lemma must share the surface's root.
//
// "2847 ✗ INSPECT" was a single undifferentiated number, which is unactionable —
// it cannot distinguish a parser bug from ordinary Hebrew morphology. Most of
// what trips a FIRST-LETTER comparison is not a bug at all:
//
//   • WEAK-INITIAL verbs. I-nun assimilates and I-waw/I-yod elide, so H5307
//     𐤍𐤐𐤋 legitimately surfaces as 𐤐𐤋 and H3427 𐤉𐤔𐤁 as 𐤔𐤁. The lemma keeps a
//     radical the surface form does not show. Correct, and unfixable by design.
//   • MATRES. The lexicon and the parse can spell the same root plene vs
//     defective; collapse them and they are identical.
//
//   What IS a bug:
//   • PREFIX RETAINED — the root still carries a proclitic (root = 𐤄 + lemma).
//     The prefix split failed for this surface.
//   • INITIAL DROPPED — the root lost a radical the lemma has and no weak-letter
//     rule explains it (lemma = X + root, X not in the weak set). Over-stripping.
//   • UNRELATED — the two share almost no consonants, so the Strong's is
//     probably just wrong for this surface.
//
// Classify, so the count separates work to do from Hebrew being Hebrew.
// ── THE INVARIANT ───────────────────────────────────────────────
// "Characters from a root are never removed. All modifications are ADDED to the
// original root." The root is the seed; a rendered word is that seed plus every
// modification spelled out — even where Hebrew orthography merges or drops one.
// 𐤀𐤌𐤓 with the 1cs "I" modifier renders 𐤀𐤀𐤌𐤓; with the 1cp nun, 𐤍𐤀𐤌𐤓.
//
// So there is exactly one thing to check: did root_paleo keep every letter of
// its Strong's root?
//
//   root-char-removed  root_paleo is missing a letter the root has. THE bug.
//   sn-mismatch        more than two root letters are absent from the SURFACE
//                      too — the Strong's probably does not belong to this word
//                      (in practice: compound proper nouns like Kiryat-Arba,
//                      where the lemma is the whole name and the token is half).
//
// NOTE, corrected: a root letter missing from the SURFACE is not itself a fault.
// An elided nun or yod is unwritten in Hebrew but still part of the root, and
// this app restores it. Adding a letter back is the design.
const _lemmaIn = (lemma, s) => isRootSubsequence([...lemma], [...s]);
const _absentFromSurface = (lemma, surface) => {
    const surf = [...(surface || '')];
    let i = 0, missing = 0;
    for (const ch of lemma) { const at = surf.indexOf(ch, i); if (at < 0) missing++; else i = at + 1; }
    return missing;
};

