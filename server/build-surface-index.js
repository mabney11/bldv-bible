/** kjv_def for a Strong's number — the same field apply-web-strongs glosses from. */
function strongsGloss(sn) {
    if (!sn) return null;
    const e = STRONGS_DICT[sn] || STRONGS_DICT[String(sn).replace(/^H/, '')];
    if (!e) return null;
    const raw = typeof e === 'string' ? e : (e.kjv_def || e.strongs_def || e.def || e.meaning);
    if (!raw) return null;
    // kjv_def is a KJV rendering list ("beginning, chief"). Kept as written apart
    // from leading dashes and collapsed whitespace, so the reader sees the same
    // text the OT pipeline shows. No truncation — a silently clipped gloss is
    // worse than a long one.
    const t = String(raw).replace(/^[\s\-\u2013\u2014:]+/, '').replace(/\s+/g, ' ').trim();
    return t || null;
}

