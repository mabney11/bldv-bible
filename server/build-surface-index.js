// ── Strong's ↔ root invariant ────────────────────────────────────────────────
// A surface's Strong's number MUST be one whose canonical lemma equals the
// surface's own parsed root. The root is trustworthy; the source SN is not (it
// mis-tags 𐤁𐤔𐤓 "proclaim" as H6666 צedaqah, leaves H9000 sentinels, etc.).
// Invert strongs-roots (H → lemma) into lemma → [H], plus a coarse POS per SN
// for homograph choice, and force every surface's SN(s) to obey the invariant
// at serialize time. surface-strongs-overrides.json still wins.
const _numH       = h => parseInt(String(h).replace(/^H+/, ''), 10) || 0;
const _normH      = s => s ? 'H' + String(s).replace(/^H+/, '') : '';
const _isVirtualSN = h => _numH(h) >= 9000;   // H9000–H9999 are placeholders, never real
const reverseStrongs = new Map();
for (const [h, paleo] of Object.entries(strongsRootsLex || {})) {
    if (!paleo) continue;
    if (!reverseStrongs.has(paleo)) reverseStrongs.set(paleo, []);
    reverseStrongs.get(paleo).push(_normH(h));
}
for (const arr of reverseStrongs.values()) arr.sort((a, b) => _numH(a) - _numH(b));
const _posOf = new Map();
try {
    const _dict = require(path.join(LEX_DIR, 'strongs-hebrew-dictionary.js'));
    for (const [h, e] of Object.entries(_dict)) {
        const d = `${e.derivation || ''} ${e.strongs_def || ''}`.toLowerCase();
        _posOf.set(_normH(h), /primitive root|to /.test(d) ? 'verb' : 'noun');
    }
} catch { /* POS optional — homograph choice falls back to the canonical lowest number */ }

// Returns { strongs, all } forced consistent with `root`. override (a pinned SN) wins.
function reconcileStrongs(root, curStrongs, curAllSet, pos, override) {
    if (override) { const o = _normH(override); return { strongs: o, all: [o] }; }
    const cands = (reverseStrongs.get(root) || []).filter(h => !_isVirtualSN(h));
    const cur = _normH(curStrongs);
    let primary;
    if (cur && !_isVirtualSN(cur) && cands.includes(cur)) {
        primary = cur;                                  // already consistent
    } else if (cands.length) {
        const wantVerb = /verb/.test(pos || '');
        const byPos = cands.filter(h => _posOf.has(h) && (_posOf.get(h) === 'verb') === wantVerb);
        primary = (byPos.length ? byPos : cands)[0];    // POS-matched, else canonical lowest
    } else {
        primary = (cur && !_isVirtualSN(cur)) ? cur : null;  // root not in lexicon: keep real SN, drop sentinel
    }
    let all = cands.length ? cands.slice()
            : [...(curAllSet || [])].map(_normH).filter(h => h && !_isVirtualSN(h));
    if (primary && !all.includes(primary)) all.unshift(primary);
    if (!all.length && primary) all = [primary];
    return { strongs: primary, all: [...new Set(all)] };
}

