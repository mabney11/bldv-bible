console.log(`Total tokens in corpus: ${total_tokens.toLocaleString()}`);

// Fetch all distinct (word_raw, pos, morph, strongs) combos — these are the
// unique parse inputs. One parse per combo covers every occurrence.
const distinctRows = src.prepare(`
    SELECT word_raw, pos, morph, strongs,
           COUNT(*) AS occurrence_count
    FROM tokens_bhs
    WHERE word_raw IS NOT NULL AND word_raw != '' AND pos != 'punct'
    GROUP BY word_raw, pos, morph, strongs
    ORDER BY word_raw
`).all();

console.log(`Distinct (word_raw, pos, morph, strongs) combos: ${distinctRows.length.toLocaleString()}`);

// ── Parse every distinct combo ────────────────────────────────────────────────
console.log('\nParsing all surface forms…');
const t0 = Date.now();

// Map: word_raw → { rendered_paleo, root_paleo, strongs, pos, morph, components_json }
// If the same word_raw appears with different morph/pos (homographs), we keep
// the most-frequent parse and record only the strongs values that belong to
// THIS token's own components — never strongs from surrounding tokens.
const surfaceMap = new Map(); // word_raw → best record

// POS classes that are single-morpheme grammar words and should never absorb
// foreign strongs numbers from other tokens in the same verse.
const SINGLE_MORPHEME_POS = new Set([
    'nmpr',  // proper nouns (YHWH, personal names, place names)
    'prep',  // standalone prepositions (𐤏𐤋, 𐤀𐤋, 𐤋, 𐤌, etc.)
    'conj',  // conjunctions (𐤅, 𐤊𐤉, etc.)
    'art',   // definite article (𐤄)
    'nega',  // negation particles (𐤋𐤀, 𐤁𐤋)
    'advb',  // adverbs
    'intj',  // interjections
    'inrg',  // interrogatives
    'prps',  // personal pronouns
    'prde',  // demonstrative pronouns
    'prin',  // interrogative pronouns
]);

let processed = 0;
for (const row of distinctRows) {
    try {
        // NOTE: surface-strongs-overrides.json is intentionally NOT applied here.
        // It is keyed by word_raw ALONE, so for a homograph surface (same glyphs,
        // two roots — e.g. 𐤍𐤇𐤕 = H5148 "lead" vs H5183 "rest") it can only pin ONE
        // SN and would silently mis-tag the other reading. The index is now keyed
        // per (word_raw, strongs) and is faithful to the authoritative per-token
        // OSHB Strong's in tokens_bhs. Genuine corrections belong upstream in the
        // ingest (or a location-keyed override), never surface-keyed here.
        const { rendered_paleo, root_paleo, components } = parseToken(
            row.word_raw, row.pos, row.morph, row.strongs
        );
        const normSN = row.strongs ? 'H' + row.strongs.replace(/^H+/, '') : '';

        // Only accumulate strongs into all_strongs when this row's SN actually
        // belongs to this surface's own morphology.  Single-morpheme grammar
        // words (proper nouns, conjunctions, prepositions, pronouns, etc.) must
        // never absorb foreign SNs — they appear in too many verse contexts and
        // their all_strongs would otherwise grow to include every SN in the Bible.
        const isSingleMorpheme = SINGLE_MORPHEME_POS.has(row.pos);

        // KEY BY (word_raw, strongs) — one record per surface *reading*. This is
        // the whole fix: a homograph surface (𐤍𐤇𐤕 = H5148 vs H5183) now yields
        // TWO records, each with its own root_paleo/components derived from ITS
        // OWN SN, instead of collapsing to a single most-frequent winner. The
        // "most-frequent parse" tie-break below now only chooses among rows that
        // already share the SAME SN (differing morph/pos), which is always safe.
        // ── BUG A FIX ────────────────────────────────────────────────────────
        // distinctRows is GROUPed BY (word_raw, pos, morph, strongs), so every
        // morphological reading is parsed correctly and separately. Keying the
        // map by (word_raw, strongs) alone then THREW ALL BUT THE MOST FREQUENT
        // READING AWAY, and the reader served that one winner to every occurrence
        // of the surface — 67,523 occurrences corpus-wide got a reading that was
        // not theirs. The key must be the full reading, exactly matching the
        // GROUP BY. (The homograph fix already widened word_raw → +strongs; this
        // finishes the same job by adding +pos +morph.)
        const rowPos   = row.pos   || '';
        const rowMorph = row.morph || '';
        const surfKey  = `${row.word_raw}\u0000${normSN}\u0000${rowPos}\u0000${rowMorph}`;
        const existing = surfaceMap.get(surfKey);
        // With the full reading in the key each surfKey is now unique per distinct
        // row, so the frequency tie-break can never discard a distinct reading.
        if (!existing || row.occurrence_count > (existing._cnt || 0)) {
            surfaceMap.set(surfKey, {
                word_raw:        row.word_raw,
                rendered_paleo,
                root_paleo,
                strongs:         normSN,
                pos:             rowPos,
                morph:           rowMorph,
                components_json: JSON.stringify(components),
                _cnt:            row.occurrence_count,
                // Per-SN records carry exactly one real SN; seed accordingly.
                all_strongs: new Set(!isSingleMorpheme && normSN ? [normSN] : []),
            });
        } else {
            // Same (word_raw, strongs), different morph — the SN is identical, so
            // there is nothing new to accumulate into all_strongs.
            const winnerIsSingle = SINGLE_MORPHEME_POS.has(existing.pos);
            if (normSN && !winnerIsSingle) existing.all_strongs.add(normSN);
        }
    } catch (err) {
        // Parsing errors are non-fatal — skip the token
        console.warn(`  ⚠ parse error for word_raw=${row.word_raw}: ${err.message}`);
    }

    processed++;
    if (processed % 5000 === 0) {
        process.stdout.write(`  ${processed.toLocaleString()} / ${distinctRows.length.toLocaleString()} combos parsed\r`);
    }
}

