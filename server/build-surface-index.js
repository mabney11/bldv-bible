// RESOLVE THE REAL WRITE TARGET (2026-08-13): in production, OUT_DB
// (/app/server/surface-index.db) is a SYMLINK entrypoint.sh points at
// $DATA_DIR/surface-index.db on the persistent bind-mounted volume — the same
