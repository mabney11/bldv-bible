/**
 * build-surface-index.js
 *
 * Run once (or after any lexicon edit) to precompute every rendered surface
 * form and its verse occurrences.  Outputs:
 *
 *   surface-index.db   — SQLite with two tables:
 *      token_surfaces     (one row per unique word_raw in the corpus)
 *      surface_occurrences (every book/chapter/verse/ordinal hit, indexed)
 *
 * Usage:
 *   node build-surface-index.js [--db path/to/corpus.db] [--out path/to/surface-index.db]
 *
 * tokens_bhs now lives in corpus.db (alongside the multilingual `verses` table),
 * so this reads from corpus.db by default. The server then opens surface-index.db
 * read-only and serves /api/surface/:word and /api/surface/:word/verses from it.
 */

